(function() {
  function injectSocialStyles() {
    if (document.getElementById("duta-social-style")) return;
    var style = document.createElement("style");
    style.id = "duta-social-style";
    style.textContent = ".social-btn-circle{width:30px;height:30px;border-radius:50%;background:#ffffff;box-shadow:0 2px 5px rgba(0,0,0,0.18);display:inline-flex;align-items:center;justify-content:center;transition:transform 0.2s ease,box-shadow 0.2s ease;text-decoration:none;border:none;flex-shrink:0;cursor:pointer}.social-btn-circle:hover{transform:scale(1.15);box-shadow:0 4px 10px rgba(0,0,0,0.28)}.footer-social-row,.duta-social-container{display:flex;align-items:center;gap:8px;flex-wrap:wrap}";
    document.head.appendChild(style);
  }

  function renderSocialLinks() {
    injectSocialStyles();
    var targets = document.querySelectorAll(".footer-social-row, .duta-social-container");
    if (!targets || targets.length === 0) return;
    var list = window.DUTA_SOCIAL_CONFIG && window.DUTA_SOCIAL_CONFIG.links ? window.DUTA_SOCIAL_CONFIG.links : [];
    var html = list.map(function(item) {
      var isMail = item.url.indexOf("mailto:") === 0;
      var relAttr = isMail ? "" : ' target="_blank" rel="noopener"';
      return '<a href="' + item.url + '"' + relAttr + ' class="social-btn social-btn-circle" title="' + item.title + '" aria-label="' + item.title + '">' + item.svg + '</a>';
    }).join("");
    targets.forEach(function(el) {
      el.innerHTML = html;
    });
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", renderSocialLinks);
  } else {
    renderSocialLinks();
  }
})();
